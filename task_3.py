def count_letters(text):
    """
    Функция подсчитывает количество каждой буквы в тексте.
    Буквы верхнего и нижнего регистра считаются одинаковыми.
    Возвращает словарь с буквами в нижнем регистре и их количеством.
    """
    letter_count = {}
    text_lower = text.lower()

    for char in text_lower:
        if char.isalpha():  # Проверяем, является ли символ буквой
            if char in letter_count:
                letter_count[char] += 1
            else:
                letter_count[char] = 1

    return letter_count


# TODO Напишите функцию calculate_frequency
def calculate_frequency(letter_dict):
    """
    Функция вычисляет частоту каждой буквы на основе словаря с подсчётом.
    Возвращает словарь с буквами и их частотами.
    """
    if not letter_dict:
        return {}

    # Вычисляем общее количество букв
    total_letters = sum(letter_dict.values())

    # Вычисляем частоту для каждой буквы
    frequency_dict = {}
    for letter, count in letter_dict.items():
        frequency = count / total_letters
        frequency_dict[letter] = round(frequency, 2)  # Округляем до 2 знаков

    return frequency_dict


